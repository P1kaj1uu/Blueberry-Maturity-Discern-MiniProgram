"""Export the supplied weights and package the lossless ONNX as small JS subpackages."""
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    from ultralytics import YOLO
    model = YOLO(ROOT / 'model/best.pt')
    assert model.names == {0: 'Immature', 1: 'Mature'}, model.names
    exported = Path(model.export(format='onnx', imgsz=640, opset=11,
                                 dynamic=False, simplify=True, nms=False))
    data = exported.read_bytes()
    chunks = [data[i:i + 1024 * 1024] for i in range(0, len(data), 1024 * 1024)]
    packages = []
    loaders = []
    for i, chunk in enumerate(chunks):
        name = f'berry_model_{i + 1:02}'
        folder = ROOT / 'miniprogram/models' / name
        folder.mkdir(parents=True, exist_ok=True)
        (folder / 'data.js').write_text('module.exports = ' + json.dumps(base64.b64encode(chunk).decode()) + '\n')
        (folder / 'placeholder.js').write_text('Page({})\n')
        (folder / 'placeholder.json').write_text('{}\n')
        (folder / 'placeholder.wxml').write_text('<view></view>\n')
        packages.append({'name': name, 'root': f'models/{name}', 'pages': ['placeholder']})
        loaders.append(f"  {{ name: '{name}', size: {len(chunk)}, read: () => require.async('../models/{name}/data.js') }}")
    manifest = "// Generated by scripts/build_device_model.py; do not edit manually.\nmodule.exports = {\n"
    manifest += f"  size: {len(data)}, md5: '{hashlib.md5(data).hexdigest()}', input: 'images', output: 'output0',\n"
    manifest += "  parts: [\n" + ',\n'.join(loaders) + '\n  ]\n}\n'
    (ROOT / 'miniprogram/utils/model-manifest.js').write_text(manifest)
    app_path = ROOT / 'miniprogram/app.json'
    app = json.loads(app_path.read_text())
    app['subPackages'] = packages
    app_path.write_text(json.dumps(app, ensure_ascii=False, indent=2) + '\n')
    total = sum(f.stat().st_size for f in (ROOT / 'miniprogram').rglob('*') if f.is_file())
    assert total < 20 * 1024 * 1024, total
    assert all(sum(f.stat().st_size for f in (ROOT / 'miniprogram' / p['root']).rglob('*') if f.is_file()) < 2 * 1024 * 1024 for p in packages)
    print(f'ONNX {len(data)} bytes; {len(chunks)} subpackages; package files total {total} bytes')


if __name__ == '__main__':
    main()
